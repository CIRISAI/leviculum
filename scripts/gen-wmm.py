#!/usr/bin/env python3
"""Generate the World Magnetic Model coefficient table leviculum-map's
declination module evaluates (leviculum-map/src/declination/coefficients.rs).

Input: WMM.COF of WMM2025 as NOAA NCEI publishes it in WMM2025COF.zip,
https://www.ncei.noaa.gov/sites/default/files/2024-12/WMM2025COF.zip
(linked from https://www.ncei.noaa.gov/products/world-magnetic-model).
The WMM is a work of the US government and in the public domain; the NCEI
page says: "The WMM source code is in the public domain and not licensed or
under copyright. The information and software may be used freely by the
public."

The file is one header line (epoch, model name, release date), then one
line per degree n and order m, 1 <= n <= 12, 0 <= m <= n, with g, h, gdot,
hdot in nT and nT per year, ended by lines of nines. The table keeps them
in the order of the WMM technical report's code: index n(n+1)/2 + m, so
index 0 (n = 0) is an unused zero.

Usage:
  python3 scripts/gen-wmm.py path/to/WMM.COF > leviculum-map/src/declination/coefficients.rs

Generating from the same file gives the same bytes.
"""

import hashlib
import os
import sys

N_MAX = 12
LEN = (N_MAX + 1) * (N_MAX + 2) // 2


def parse(text):
    lines = [ln for ln in text.splitlines() if ln.strip()]
    head = lines[0].split()
    epoch = float(head[0])
    name = head[1]
    released = head[2] if len(head) > 2 else ""
    g = [0.0] * LEN
    h = [0.0] * LEN
    gd = [0.0] * LEN
    hd = [0.0] * LEN
    seen = set()
    for ln in lines[1:]:
        if ln.startswith("9999"):
            break
        f = ln.split()
        n, m = int(f[0]), int(f[1])
        if not (1 <= n <= N_MAX and 0 <= m <= n):
            raise SystemExit(f"gen-wmm: degree/order out of range: {ln!r}")
        i = n * (n + 1) // 2 + m
        if i in seen:
            raise SystemExit(f"gen-wmm: duplicate term: {ln!r}")
        seen.add(i)
        g[i], h[i], gd[i], hd[i] = (float(x) for x in f[2:6])
    if len(seen) != LEN - 1:
        raise SystemExit(f"gen-wmm: {len(seen)} terms, expected {LEN - 1}")
    return epoch, name, released, g, h, gd, hd


def fmt(x):
    s = repr(x)
    if "e" not in s and "." not in s:
        s += ".0"
    return s


def table(name, doc, values):
    out = [f"/// {doc}", f"pub const {name}: [f64; LEN] = ["]
    for n in range(N_MAX + 1):
        row = values[n * (n + 1) // 2 : (n + 1) * (n + 2) // 2]
        out.append(f"    // n = {n}")
        out.append("    " + ", ".join(fmt(v) for v in row) + ",")
    out.append("];")
    return "\n".join(out)


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    path = sys.argv[1]
    with open(path, "rb") as f:
        raw = f.read()
    digest = hashlib.sha256(raw).hexdigest()
    epoch, name, released, g, h, gd, hd = parse(raw.decode("ascii"))
    base = os.path.basename(path)
    parts = [
        "// Generated by scripts/gen-wmm.py; do not edit.",
        "//",
        f"// Source: {base} of {name} (released {released}), NOAA NCEI and",
        "// BGS, from https://www.ncei.noaa.gov/sites/default/files/2024-12/WMM2025COF.zip",
        f"// sha256 of {base}: {digest}",
        "// Licence: public domain, a work of the US government. NCEI: \"The WMM",
        "// source code is in the public domain and not licensed or under",
        "// copyright. The information and software may be used freely by the",
        "// public.\" (https://www.ncei.noaa.gov/products/world-magnetic-model)",
        "//",
        "// Regenerate with",
        f"//   python3 scripts/gen-wmm.py path/to/{base} > leviculum-map/src/declination/coefficients.rs",
        "",
        "//! The WMM2025 Gauss coefficients, indexed n(n+1)/2 + m; index 0 is unused.",
        "",
        "/// The name the coefficient file gives the model.",
        f'pub const MODEL: &str = "{name}";',
        "",
        "/// The model's epoch, a decimal year; the secular variation runs from it.",
        f"pub const EPOCH: f64 = {fmt(epoch)};",
        "",
        "/// The highest degree and order of the model.",
        f"pub const N_MAX: usize = {N_MAX};",
        "",
        "/// The length of each table, (N_MAX + 1)(N_MAX + 2) / 2.",
        f"pub const LEN: usize = {LEN};",
        "",
        table("G", "Main field g, nT.", g),
        "",
        table("H", "Main field h, nT.", h),
        "",
        table("G_DOT", "Secular variation of g, nT per year.", gd),
        "",
        table("H_DOT", "Secular variation of h, nT per year.", hd),
        "",
    ]
    sys.stdout.write("\n".join(parts))


if __name__ == "__main__":
    main()
